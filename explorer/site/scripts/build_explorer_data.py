def rd_tsv(p):
    with open(p, newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def sheet(path, name, header_row):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    rows = list(wb[name].iter_rows(values_only=True))
    hdr = [str(h) if h is not None else "" for h in rows[header_row]]
    return [dict(zip(hdr, r)) for r in rows[header_row + 1:] if r and r[0] is not None]


def tf(x):
    return str(x).strip().upper() in ("TRUE", "YES", "T", "1")


def dedup(seq):
    out = []
    for x in seq:
        if x and x not in out:
            out.append(x)
    return out


def coloc_terms(cclass):
    if cclass in ("strong_PP4", "moderate_PP4"): return ["coloc", "colocalisation", "PP4", "shared signal"]
    if cclass == "PP3_only": return ["coloc", "PP3", "regional", "regional overlap"]
    if cclass == "not_assessed": return ["coloc not assessed"]
    return ["no coloc"]


def wj(obj, name):
    with open(os.path.join(SITE_DATA, name), "w", encoding="utf-8") as fh:
        json.dump(obj, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def wtsv(rows, name, cols=None):
    cols = cols or list(rows[0].keys())
    with open(os.path.join(SRC, name), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols, delimiter="\t", lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c, "") for c in cols})


