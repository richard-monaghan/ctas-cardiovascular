def praw(gene):
    r = ukbb[gene]
    return {t: (float(r[t]) if r[t] not in ("", "NA") else None) for t in TABLE1_ORDER}


def tier_of(lid):
    a = arch[lid]
    if tf(a["in_q001"]): return "q<0.001"
    if tf(a["in_q01"]): return "q<0.01"
    return "q<0.05"


def lead_family(a):
    s = {f: float(a["S_" + f]) for f in FAM_KEYS}
    o = sorted(FAM_KEYS, key=lambda f: (-s[f], FAM_KEYS.index(f)))
    k1, k2 = o[0], o[1]
    v1, v2 = s[k1], s[k2]
    dual = v1 > 0 and v2 >= 0.9 * v1
    if dual:
        return ([k1, k2], f"{FAM_LAB_DISPLAY[k1]} / {FAM_LAB_DISPLAY[k2]}",
                f"{FAM_LAB_DISPLAY[k1]} {v1*100:.1f}% / {FAM_LAB_DISPLAY[k2]} {v2*100:.1f}%")
    return [k1], FAM_LAB_DISPLAY[k1], f"{FAM_LAB_DISPLAY[k1]} {v1*100:.1f}%"


